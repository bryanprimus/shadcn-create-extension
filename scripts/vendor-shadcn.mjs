// Regenerates components/ui from a shadcn/ui checkout, producing the same
// base-nova files `shadcn add` installs for a Base UI + Nova project:
// the style-agnostic sources in registry/bases/base/ui get their `cn-*`
// placeholder classes replaced by the Nova utilities from
// registry/styles/style-nova.css, and icon placeholders become lucide icons.
//
// Usage: node scripts/vendor-shadcn.mjs <path to shadcn-ui/ui checkout>

import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import postcss from "postcss"
import selectorParser from "postcss-selector-parser"
import { twMerge } from "tailwind-merge"

// From packages/shadcn/src/styles/transform-style-map.ts.
const ALLOWLIST = new Set([
  "cn-menu-target",
  "cn-menu-translucent",
  "cn-logical-sides",
  "cn-rtl-flip",
  "cn-font-heading",
])

const COMPONENTS = ["button", "input", "textarea", "input-group", "combobox"]

const repo = process.argv[2]
if (!repo) {
  console.error("Usage: node scripts/vendor-shadcn.mjs <shadcn-ui/ui checkout>")
  process.exit(1)
}
const v4 = resolve(repo, "apps/v4")
const out = resolve(import.meta.dirname, "../components/ui")

// Same rules as shadcn's createStyleMap (packages/shadcn/src/styles):
// every rule's @apply classes belong to the last cn-* class in its selector.
const styleMap = createStyleMap(
  readFileSync(resolve(v4, "registry/styles/style-nova.css"), "utf8")
)

const commit = process.env.SHADCN_COMMIT ?? "unknown"

for (const component of COMPONENTS) {
  let source = readFileSync(
    resolve(v4, `registry/bases/base/ui/${component}.tsx`),
    "utf8"
  )

  // Icon placeholders -> lucide-react, the create page's default library.
  const icons = new Set()
  source = source.replace(/<IconPlaceholder\b([\s\S]*?)\/>/g, (_, attrs) => {
    const icon = attrs.match(/lucide="(\w+)"/)?.[1]
    if (!icon) throw new Error(`No lucide icon in ${component}: ${attrs}`)
    icons.add(icon)
    const className = attrs.match(/className=("[^"]*"|\{[^}]*\})/)?.[1]
    return className ? `<${icon} className=${className} />` : `<${icon} />`
  })
  source = source.replace(/^import \{ IconPlaceholder \}.*\n/m, "")
  if (icons.size) {
    source = source.replace(
      /(import \{ cn \} from "cn"\n)/,
      `$1import { ${[...icons].sort().join(", ")} } from "lucide-react"\n`
    )
  }

  source = source
    .replace(/from "cn"/g, 'from "@/lib/utils"')
    .replace(/@\/registry\/bases\/base\/ui\//g, "@/components/ui/")

  // Placeholder classes inside string literals -> Nova utilities, merged the
  // way shadcn's transformStyleMap does. Allowlisted classes stay as is.
  source = source.replace(/"([^"\n]*\bcn-[^"\n]*)"/g, (_, value) => {
    const placeholders = value.match(/\bcn-[\w-]+\b/g) ?? []
    const styles = placeholders
      .filter((name) => !ALLOWLIST.has(name))
      .map((name) => styleMap[name])
      .filter(Boolean)
      .join(" ")
    const rest = value
      .replace(/\bcn-[\w-]+\b/g, (name) => (ALLOWLIST.has(name) ? name : ""))
      .replace(/\s+/g, " ")
      .trim()
    return `"${twMerge(styles, rest)}"`
  })

  source = applyPatches(component, source)

  const header = `// Generated by scripts/vendor-shadcn.mjs from shadcn-ui/ui@${commit}\n// (registry/bases/base/ui/${component}.tsx + style-nova.css). Do not edit.\n`
  writeFileSync(resolve(out, `${component}.tsx`), header + source)
  console.log(`components/ui/${component}.tsx`)
}

// The extension renders inside a shadow root, so popups must portal into it
// rather than document.body. This is the only change to shadcn's source.
function applyPatches(component, source) {
  if (component !== "combobox") return source
  const patched = source
    .replace(
      /(function ComboboxContent\(\{\n(?:.*\n)*?)(  \.\.\.props\n\}: ComboboxPrimitive\.Popup\.Props &\n)/,
      "$1  container,\n$2  Pick<ComboboxPrimitive.Portal.Props, \"container\"> &\n"
    )
    .replace(
      /(function ComboboxContent[\s\S]*?)<ComboboxPrimitive\.Portal>/,
      "$1<ComboboxPrimitive.Portal container={container}>"
    )
  if (!patched.includes("<ComboboxPrimitive.Portal container={container}>")) {
    throw new Error("ComboboxContent portal patch did not apply")
  }
  return patched
}

// Port of packages/shadcn/src/styles/create-style-map.ts.
function createStyleMap(input) {
  const result = {}
  postcss.parse(input).walkRules((rule) => {
    const classes = (rule.nodes ?? [])
      .filter((node) => node.type === "atrule" && node.name === "apply")
      .map((node) => node.params.trim())
      .filter(Boolean)
      .join(" ")
    if (!classes) return
    for (const selector of rule.selectors ?? []) {
      selectorParser((root) => {
        root.each((sel) => {
          const names = []
          sel.walkClasses((node) => {
            if (node.value.startsWith("cn-")) names.push(node.value)
          })
          const name = names.at(-1)
          if (!name) return
          result[name] = result[name] ? `${classes} ${result[name]}` : classes
        })
      }).processSync(selector.replace(/\s*&\s*/g, "").trim())
    }
  })
  return result
}
